#!/usr/bin/env node
/**
 * Slices game logic out of main.pretty.js and emits a shimmed ES module
 * the Angular app can import (tables, models, DataService, SaveService,
 * CoreEngine, AiEngine).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pretty = readFileSync(join(root, 'decompiled/main.pretty.js'), 'utf8').split(/\r?\n/);

function slice(start1, end1) {
  return pretty.slice(start1 - 1, end1).join('\n');
}

// Tables → SaveService (includes icons, config, models, toast/kong/data/save)
let logic = slice(23140, 34551);
// Core simulation engine
const core = slice(39259, 40712);
// AI engine
const ai = slice(41728, 42599);

logic = logic.replace(
  /var Dg = e\("NFKh"\),\s*Mg = e\("16wW"\);/,
  '/* crypto/pako injected via Dg/Mg above */',
);

/** Angular compiler rejects undecorated classes with lifecycle hooks. */
function demangleAngular(source) {
  return source
    .replace(/\bngOnDestroy\s*\(/g, 'legacyDestroy(')
    .replace(/\bngOnInit\s*\(/g, 'legacyInit(')
    .replace(/\bngOnChanges\s*\(/g, 'legacyChanges(')
    .replace(/\bngAfterViewInit\s*\(/g, 'legacyAfterViewInit(');
}

logic = demangleAngular(logic);
const coreFixed = demangleAngular(core);
const aiFixed = demangleAngular(ai);

const outDir = join(root, 'decompiled/angular-src/src/app/legacy');
mkdirSync(outDir, { recursive: true });

const header = `/**
 * AUTO-GENERATED by scripts/build-game-kernel.mjs — do not edit by hand.
 * Source: decompiled/main.pretty.js (View Engine AOT bundle).
 */
import * as CryptoJS from 'crypto-js';
import * as pako from 'pako';
import { interval } from 'rxjs';

const Pr = { production: false };
const gl = (def) => def;
const ql = (token) => token;
const om = (_due = 0, period = 1000) => interval(Number(period) || 1000);

function binaryStringFromUint8(arr) {
  let s = '';
  for (let i = 0; i < arr.length; i++) s += String.fromCharCode(arr[i]);
  return s;
}
function uint8FromBinaryString(s) {
  const out = new Uint8Array(s.length);
  for (let i = 0; i < s.length; i++) out[i] = s.charCodeAt(i) & 0xff;
  return out;
}

const Dg = CryptoJS;
const Mg = {
  gzip(str, opts) {
    const bytes = pako.gzip(str);
    if (opts && opts.to === 'string') return binaryStringFromUint8(bytes);
    return bytes;
  },
  ungzip(str, opts) {
    const bytes = typeof str === 'string' ? uint8FromBinaryString(str) : str;
    return pako.ungzip(bytes, { to: 'string' });
  },
};

`;

const footer = `

export {
  ug as ICONS,
  Tg as GameConfig,
  Eg as PlayerModel,
  Ag as CityModel,
  Pg as GameDataModel,
  Og as SaveRecordModel,
  Ng as MathUtil,
  mg as FormatUtil,
  yg as RandomUtil,
  Rg as LegacyToastService,
  Bg as LegacyKongService,
  zg as LegacyDataService,
  $g as LegacySaveService,
  vv as LegacyCoreEngine,
  qv as LegacyAiEngine,
  Pr as ENVIRONMENT,
};
`;

const body = `${logic}\n\n${coreFixed}\n\n${aiFixed}\n`;

writeFileSync(join(outDir, 'game-kernel.js'), header + body + footer);
console.log(
  'Wrote',
  join(outDir, 'game-kernel.js'),
  `(${(header + body + footer).length} bytes)`,
);
